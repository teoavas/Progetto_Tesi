from funzione import move_gain

def test_move_gain_1():
    match = [0, 1, 2]
    i = 1
    m = 10
    nm = 20
    weight_dict = {(1, 10): [5, 3], (1, 20): [7, 4]}
    match_num_dict = {(0, 1, 2): 100}
    match_num = 50
    assert move_gain(match, i, m, nm, weight_dict, match_num_dict, match_num) == 5

